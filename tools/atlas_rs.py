#!/usr/bin/env python3
"""Writes engine/src/atlas_data.rs from engine/data/atlas.png and atlas.json.

    python tools/atlas_rs.py

Horizon's registry check (at the Horizon revision it pins) accepts only
`.rs` and `.toml` files in a native bundle, so the packed atlas ships as Rust
constants: the PNG's exact bytes and the manifest's exact text. Nothing is
re-encoded; a unit test compares the constants with the files byte for byte.
"""

import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENGINE = ROOT / "mixins" / "visuality_horizon" / "engine"


def main():
    png = (ENGINE / "data" / "atlas.png").read_bytes()
    js = (ENGINE / "data" / "atlas.json").read_bytes().replace(b"\r\n", b"\n").decode("utf-8")
    if '"#' in js:
        raise SystemExit("atlas.json contains a raw-string terminator")
    lines = []
    for i in range(0, len(png), 24):
        lines.append("    " + " ".join(f"0x{b:02x}," for b in png[i:i + 24]))
    out = (
        "// Generated by tools/atlas_rs.py from engine/data/atlas.png and atlas.json (do not edit).\n"
        f"// atlas.png: {len(png)} bytes, SHA-256 {hashlib.sha256(png).hexdigest()}.\n"
        "// The art is rendered in Blender from art/blender/ in the source repository.\n\n"
        "/// The packed particle atlas, PNG bytes exactly as rendered and packed.\n"
        f"pub const ATLAS_PNG: &[u8; {len(png)}] = &[\n" + "\n".join(lines) + "\n];\n\n"
        "/// The atlas manifest (atlas.json).\n"
        f'pub const ATLAS_JSON: &str = r#"{js}"#;\n'
    )
    (ENGINE / "src" / "atlas_data.rs").write_text(out, encoding="utf-8", newline="\n")
    print(f"atlas_data.rs: {len(png)} PNG bytes, {len(js)} manifest bytes")


if __name__ == "__main__":
    main()
